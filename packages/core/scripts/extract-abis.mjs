// Copies ABIs from forge `out/` into packages/core/abis as TS consts (viem-typed).
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const out = resolve(here, "../../../contracts/out");
const dest = resolve(here, "../abis");
mkdirSync(dest, { recursive: true });

for (const name of ["PaymentMandate", "SpendingPolicy", "PaymentStream", "MockUSDC"]) {
  const artifact = JSON.parse(readFileSync(resolve(out, `${name}.sol/${name}.json`), "utf8"));
  const body = `// generated by scripts/extract-abis.mjs — do not edit\nexport const ${name}Abi = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`;
  writeFileSync(resolve(dest, `${name}.ts`), body);
  console.log("wrote", name);
}
